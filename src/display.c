void display_task(void *argument){
    spi_init();
    spi_dma_init();
    osMessageQueueId_t *display_queue_id = (osMessageQueueId_t *)argument;
    struct sh1106_dev sh1106 = {
      .a0 = {.pin = OLED_A0_Pin, .port = (void *)OLED_A0_GPIO_Port},
      .rst = {.pin = OLED_RES_Pin, .port = (void *)OLED_RES_GPIO_Port},
      .cs = {.pin = OLED_CS_Pin, .port = (void *)OLED_CS_GPIO_Port},
      .reset = sh1106_reset, .write = sh1106_write
    };

    sh1106_init(&sh1106);
    sh1106_send_cmd_list(&sh1106, init_cmds, sizeof(init_cmds));
    sh1106_clear(&sh1106);
    draw(&sh1106, LED, 52, 16, 38, 14);
    sh1106_update_region(&sh1106, 0, 0, 128, 64);

    display_event d_event;
    bool active = true;
    while(1){
        osStatus_t status = osMessageQueueGet(*display_queue_id, (void *)&d_event, NULL, DISPLAY_TIMEOUT_MS);
        if(status == osOK){
            if(active){
                sh1106_clear(&sh1106);
                update_state(&sh1106, &d_event);
                sh1106_update_region(&sh1106, 0, 0, 128, 64);
            }
            else{
                sh1106_send_cmd(&sh1106, SH1106_SET_DISPLAY | 0x1);
                active = true;
            }
        }
        else if(status == osErrorTimeout && active){
            active = false;
            sh1106_send_cmd(&sh1106, SH1106_SET_DISPLAY);
        }
    }
}

static void sh1106_reset(){
    LL_GPIO_ResetOutputPin(OLED_RES_GPIO_Port, OLED_RES_Pin);
    osDelay(1);
    LL_GPIO_SetOutputPin(OLED_RES_GPIO_Port, OLED_RES_Pin);
}

static void sh1106_write(struct sh1106_dev *ctx, uint8_t *bytes, const uint8_t n_bytes, bool data){
    osThreadFlagsWait(0x1, osFlagsWaitAny, osWaitForever);
    if(data){
        LL_GPIO_SetOutputPin(ctx->a0.port, ctx->a0.pin);
        spi_dma_transmit(bytes, n_bytes);
    }
    else{
        LL_GPIO_ResetOutputPin(ctx->a0.port, ctx->a0.pin);
        spi_transmit(bytes, n_bytes);
        osThreadFlagsSet(spi_thread_id, 0x1);
    }
}

static void draw(struct sh1106_dev *sh1106, uint8_t *bytes, uint8_t w, uint8_t h, int x, int y){
    int init_page = y / 8;
    int pages = (y + h) / 8 - init_page;
    uint8_t y_shift = y % 8;
    for(int i = 0; i < pages; i++){
        for(int j = 0; j < w; j++){
            int buf_idx = (init_page + i) * DISPLAY_WIDTH + x + j;
            if(y_shift){
                sh1106->buffer[buf_idx] &= ~(0xFF << y_shift);
                sh1106->buffer[buf_idx + DISPLAY_WIDTH] &= ~(0xFF >> (8 - y_shift));
                uint8_t upper_bits = bytes[i * w + j] << y_shift;
                uint8_t lower_bits = bytes[i * w + j] >> (8 - y_shift);
                sh1106->buffer[buf_idx] |= upper_bits;
                sh1106->buffer[buf_idx + DISPLAY_WIDTH] |= lower_bits;
            }
            else{
                sh1106->buffer[buf_idx] = bytes[i * w + j];
            }
        }
    }
}

static void update_state(struct sh1106_dev *sh1106, display_event *current){
    sh1106_clear(sh1106);
    switch(current->mode){
        case MODE_LED_DISPLAY:
            draw(sh1106, LED, 52, 16, 38, 14);
            switch(current->val){
                case LED_DISPLAY_OFF:
                    draw(sh1106, LED_OFF, 52, 16, 38, 34);
                    break;
                case LED_DISPLAY_BLINK:
                    draw(sh1106, LED_BLINK, 52, 16, 38, 34);
                    break;
                case LED_DISPLAY_ON:
                    draw(sh1106, LED_ON, 52, 16, 38, 34);
                    break;
                default:
                    break;
            }
            break;
        case MODE_LED_PWM:
            draw(sh1106, PWM, 52, 16, 38, 14);
            draw(sh1106, DISPLAY_DIGITS.bytes[current->val / 100], 8, 16, 42, 34);
            draw(sh1106, DISPLAY_DIGITS.bytes[(current->val / 10) % 10], 8, 16, 60, 34);
            draw(sh1106, DISPLAY_DIGITS.bytes[current->val % 10], 8, 16, 78, 34);
            break;
        default:
            break;
    }
}